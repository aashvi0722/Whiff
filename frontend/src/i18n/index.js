export function t(code, lang = 'en', params = {}) {
  const text = dictionary[lang]?.[code] ?? dictionary.en[code]
  if (text === undefined) {
    if (import.meta.env.DEV) console.warn(`[i18n] missing key: ${code}`)
    return code
  }
  return text.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '')
}
export const reasonText = (r, lang) => t(r.code, lang, r.params || {})

export function tryT(code, lang = 'en', params = {}) {
  const has = dictionary[lang]?.[code] ?? dictionary.en[code]
  return has === undefined ? null : t(code, lang, params)
}
